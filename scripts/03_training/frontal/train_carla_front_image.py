import argparse
import csv
import importlib.util
import random
from pathlib import Path

import cv2
import numpy as np
import torch
from PIL import Image
from torch.utils.data import DataLoader, Dataset, Subset

PILOTNET_PATH = Path(__file__).resolve().parents[1] / "brains/CARLA/utils/pilotnet.py"
PILOTNET_SPEC = importlib.util.spec_from_file_location("behavior_metrics_pilotnet", PILOTNET_PATH)
if PILOTNET_SPEC is None or PILOTNET_SPEC.loader is None:
    raise ImportError(f"Could not load PilotNet from {PILOTNET_PATH}")
PILOTNET_MODULE = importlib.util.module_from_spec(PILOTNET_SPEC)
PILOTNET_SPEC.loader.exec_module(PILOTNET_MODULE)
PilotNet = PILOTNET_MODULE.PilotNet


class FrontImageDataset(Dataset):
    """Reads the driving_log.csv generated by the CARLA log extractor."""

    def __init__(self, csv_path):
        self.csv_path = Path(csv_path).resolve()
        self.samples = []
        self.source_logs = []
        with self.csv_path.open(newline="", encoding="utf-8-sig") as file:
            reader = csv.DictReader(file)
            columns = set(reader.fieldnames or [])
            image_column = "image_path" if "image_path" in columns else "image"
            steer_column = "steering" if "steering" in columns else "steer"
            required_columns = {image_column, "throttle", steer_column}
            if not required_columns.issubset(columns):
                raise ValueError(
                    "CSV must contain image_path (or image), throttle, and "
                    "steering (or steer) columns"
                )

            for line_number, row in enumerate(reader, start=2):
                image_path = Path(row[image_column])
                if not image_path.is_absolute():
                    image_path = self.csv_path.parent / image_path
                try:
                    throttle = float(row["throttle"])
                    steer = float(row[steer_column])
                except (TypeError, ValueError) as error:
                    raise ValueError(f"Invalid control value on CSV line {line_number}") from error
                if not 0.0 <= throttle <= 1.0:
                    raise ValueError(f"Throttle must be in [0, 1] on CSV line {line_number}")
                if not -1.0 <= steer <= 1.0:
                    raise ValueError(f"Steering must be in [-1, 1] on CSV line {line_number}")
                if not image_path.is_file():
                    raise FileNotFoundError(f"Image on CSV line {line_number} not found: {image_path}")
                self.samples.append((image_path, throttle, steer))
                self.source_logs.append(row.get("source_log", "").strip())

        if len(self.samples) < 2:
            raise ValueError("At least two labeled image rows are required for train/validation split")

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, index):
        image_path, throttle, steer = self.samples[index]
        with Image.open(image_path) as image_file:
            image = np.asarray(image_file.convert("RGB"))

        if image.shape[0] < 480 or image.shape[1] < 640:
            raise ValueError(
                f"{image_path} must be at least 640x480 to match the brain's crop; "
                f"got {image.shape[1]}x{image.shape[0]}"
            )

        image = image[240:480, 0:640]
        image = cv2.resize(image, (200, 66))
        image_tensor = torch.from_numpy(image.copy()).permute(2, 0, 1).float().div_(255.0)
        control = torch.tensor([throttle, steer], dtype=torch.float32)
        return image_tensor, control


def split_dataset(dataset, validation_fraction, seed):
    unique_logs = sorted(set(dataset.source_logs))
    if len(unique_logs) > 1 and all(dataset.source_logs):
        random.Random(seed).shuffle(unique_logs)
        target_validation_count = max(1, round(len(dataset) * validation_fraction))
        validation_logs = set()
        validation_count = 0
        for source_log in unique_logs[:-1]:
            validation_logs.add(source_log)
            validation_count += dataset.source_logs.count(source_log)
            if validation_count >= target_validation_count:
                break

        validation_indices = [
            index for index, source_log in enumerate(dataset.source_logs)
            if source_log in validation_logs
        ]
        training_indices = [
            index for index, source_log in enumerate(dataset.source_logs)
            if source_log not in validation_logs
        ]
        return Subset(dataset, training_indices), Subset(dataset, validation_indices), "by source_log"

    validation_count = min(max(1, round(len(dataset) * validation_fraction)), len(dataset) - 1)
    indices = torch.randperm(len(dataset), generator=torch.Generator().manual_seed(seed)).tolist()
    validation_indices = indices[:validation_count]
    training_indices = indices[validation_count:]
    return Subset(dataset, training_indices), Subset(dataset, validation_indices), "by frame"


def evaluate(model, loader, loss_function, device):
    model.eval()
    total_loss = 0.0
    sample_count = 0
    with torch.no_grad():
        for images, controls in loader:
            images = images.to(device)
            controls = controls.to(device)
            loss = loss_function(model(images), controls)
            total_loss += loss.item() * images.size(0)
            sample_count += images.size(0)
    return total_loss / sample_count


def main():
    parser = argparse.ArgumentParser(
        description=(
            "Train the PilotNet loaded by brain_carla_front_image_api.py from "
            "the extractor's driving_log.csv (image_path, throttle, steering)."
        )
    )
    parser.add_argument("csv", type=Path, help="Path to driving_log.csv")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "models/CARLA/front_image_pilotnet.pth",
        help="Output state_dict path (default: behavior_metrics/models/CARLA/front_image_pilotnet.pth)",
    )
    parser.add_argument("--epochs", type=int, default=30)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--learning-rate", type=float, default=1e-4)
    parser.add_argument("--validation-fraction", type=float, default=0.2)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--workers", type=int, default=0)
    parser.add_argument("--device", choices=("auto", "cpu", "cuda"), default="auto")
    args = parser.parse_args()

    if args.epochs < 1 or args.batch_size < 1 or args.learning_rate <= 0:
        parser.error("epochs and batch-size must be positive; learning-rate must be greater than zero")
    if not 0.0 < args.validation_fraction < 1.0:
        parser.error("validation-fraction must be between 0 and 1")
    if args.workers < 0:
        parser.error("workers cannot be negative")
    if args.device == "cuda" and not torch.cuda.is_available():
        parser.error("CUDA was requested but is not available")

    random.seed(args.seed)
    np.random.seed(args.seed)
    torch.manual_seed(args.seed)
    if args.device == "auto":
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    else:
        device = torch.device(args.device)

    dataset = FrontImageDataset(args.csv)
    training_data, validation_data, split_mode = split_dataset(
        dataset, args.validation_fraction, args.seed
    )
    training_loader = DataLoader(
        training_data,
        batch_size=args.batch_size,
        shuffle=True,
        num_workers=args.workers,
        pin_memory=device.type == "cuda",
    )
    validation_loader = DataLoader(
        validation_data,
        batch_size=args.batch_size,
        shuffle=False,
        num_workers=args.workers,
        pin_memory=device.type == "cuda",
    )

    model = PilotNet((66, 200), 2).to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=args.learning_rate)
    loss_function = torch.nn.MSELoss()
    best_validation_loss = float("inf")
    args.output.parent.mkdir(parents=True, exist_ok=True)

    print(
        f"Training on {len(training_data)} images; validating on {len(validation_data)}; "
        f"split={split_mode}; device={device}"
    )
    for epoch in range(1, args.epochs + 1):
        model.train()
        total_training_loss = 0.0
        seen_samples = 0
        for images, controls in training_loader:
            images = images.to(device)
            controls = controls.to(device)
            optimizer.zero_grad(set_to_none=True)
            loss = loss_function(model(images), controls)
            loss.backward()
            optimizer.step()
            total_training_loss += loss.item() * images.size(0)
            seen_samples += images.size(0)

        training_loss = total_training_loss / seen_samples
        validation_loss = evaluate(model, validation_loader, loss_function, device)
        print(
            f"epoch {epoch:03d}/{args.epochs}: "
            f"train_mse={training_loss:.6f} val_mse={validation_loss:.6f}"
        )

        if validation_loss < best_validation_loss:
            best_validation_loss = validation_loss
            cpu_state_dict = {
                name: tensor.detach().cpu() for name, tensor in model.state_dict().items()
            }
            torch.save(cpu_state_dict, args.output)

    print(f"Best validation MSE: {best_validation_loss:.6f}")
    print(f"Saved compatible PilotNet state_dict to: {args.output}")


if __name__ == "__main__":
    main()